const { APPLICATION_STATUS } = require("../constants/enums");

const TRANSITIONS = Object.freeze({
  [APPLICATION_STATUS.APPLIED]: [APPLICATION_STATUS.UNDER_REVIEW, APPLICATION_STATUS.SHORTLISTED, APPLICATION_STATUS.ON_HOLD, APPLICATION_STATUS.REJECTED],
  [APPLICATION_STATUS.UNDER_REVIEW]: [APPLICATION_STATUS.SHORTLISTED, APPLICATION_STATUS.TECHNICAL_ROUND, APPLICATION_STATUS.ON_HOLD, APPLICATION_STATUS.REJECTED],
  [APPLICATION_STATUS.SHORTLISTED]: [APPLICATION_STATUS.INTERVIEW_SCHEDULED, APPLICATION_STATUS.TECHNICAL_ROUND, APPLICATION_STATUS.HR_ROUND, APPLICATION_STATUS.ON_HOLD, APPLICATION_STATUS.REJECTED],
  [APPLICATION_STATUS.INTERVIEW_SCHEDULED]: [APPLICATION_STATUS.TECHNICAL_ROUND, APPLICATION_STATUS.HR_ROUND, APPLICATION_STATUS.REJECTED, APPLICATION_STATUS.ON_HOLD],
  [APPLICATION_STATUS.TECHNICAL_ROUND]: [APPLICATION_STATUS.HR_ROUND, APPLICATION_STATUS.SELECTED, APPLICATION_STATUS.REJECTED, APPLICATION_STATUS.ON_HOLD],
  [APPLICATION_STATUS.HR_ROUND]: [APPLICATION_STATUS.SELECTED, APPLICATION_STATUS.REJECTED, APPLICATION_STATUS.ON_HOLD],
  [APPLICATION_STATUS.ON_HOLD]: [APPLICATION_STATUS.UNDER_REVIEW, APPLICATION_STATUS.SHORTLISTED, APPLICATION_STATUS.REJECTED],
  [APPLICATION_STATUS.REJECTED]: [],
  [APPLICATION_STATUS.SELECTED]: [],
  [APPLICATION_STATUS.REVIEWED]: [APPLICATION_STATUS.SHORTLISTED, APPLICATION_STATUS.REJECTED, APPLICATION_STATUS.INTERVIEW_SCHEDULED],
  [APPLICATION_STATUS.SCREENING]: [APPLICATION_STATUS.SHORTLISTED, APPLICATION_STATUS.REJECTED],
  [APPLICATION_STATUS.INTERVIEW]: [APPLICATION_STATUS.INTERVIEW_COMPLETED, APPLICATION_STATUS.REJECTED],
  [APPLICATION_STATUS.INTERVIEW_COMPLETED]: [APPLICATION_STATUS.SELECTED, APPLICATION_STATUS.REJECTED],
  [APPLICATION_STATUS.OFFERED]: [APPLICATION_STATUS.SELECTED, APPLICATION_STATUS.REJECTED],
  [APPLICATION_STATUS.WITHDRAWN]: []
});

function canTransition(from, to) {
  if (!from || !to) return false;
  if (from === to) return true;
  return (TRANSITIONS[from] || []).includes(to);
}

module.exports = { TRANSITIONS, canTransition };
