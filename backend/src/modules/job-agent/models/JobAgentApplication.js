const mongoose = require("mongoose");

const JOB_AGENT_STATUS = ["saved", "interested", "applied", "interview", "rejected"];

const jobAgentApplicationSchema = new mongoose.Schema(
  {
    user: { type: mongoose.Schema.Types.ObjectId, ref: "User", required: true, index: true },
    internProfile: { type: mongoose.Schema.Types.ObjectId, ref: "InternProfile", required: true, index: true },

    // "internal" | "remotive" | "adzuna"
    jobSource: { type: String, required: true, trim: true },
    // For internal: the Internship _id as a string. For external: the
    // provider's sourceId. Combined with jobSource this is the dedup key.
    jobRef: { type: String, required: true, trim: true },

    internshipId: { type: mongoose.Schema.Types.ObjectId, ref: "Internship", default: null },
    externalJobId: { type: mongoose.Schema.Types.ObjectId, ref: "ExternalJobListing", default: null },

    // Denormalized display snapshot so the tracker never needs a join and
    // keeps working even if an external listing later falls out of the
    // refreshed cache.
    snapshot: {
      title: { type: String, default: "", trim: true },
      companyName: { type: String, default: "", trim: true },
      location: { type: String, default: "", trim: true },
      applyUrl: { type: String, default: "", trim: true },
      // Carried over at track-time so the application assistant can
      // generate tailored materials later without re-joining back to a
      // listing that may since have rotated out of the external cache.
      skillsRequired: [{ type: String, trim: true }],
      prioritySkills: [{ type: String, trim: true }]
    },

    fitScore: { type: Number, default: null, min: 0, max: 100 },

    status: { type: String, enum: JOB_AGENT_STATUS, default: "saved" },
    statusHistory: [
      {
        status: { type: String, enum: JOB_AGENT_STATUS },
        note: { type: String, default: "", trim: true },
        changedAt: { type: Date, default: Date.now }
      }
    ],

    // Application-assistant output. Template-generated by default; if a
    // GROQ_API_KEY is configured the text may come from the LLM instead
    // (see job-agent/services/application-assistant.service.js).
    tailoredResume: {
      content: { type: String, default: "" },
      generatedAt: { type: Date, default: null },
      source: { type: String, default: "" } // "template" | "groq" | "huggingface"
    },
    coverLetter: {
      content: { type: String, default: "" },
      generatedAt: { type: Date, default: null },
      source: { type: String, default: "" }
    },

    notes: { type: String, default: "", trim: true }
  },
  { timestamps: true }
);

jobAgentApplicationSchema.pre("validate", function stampStatusHistory(next) {
  if (this.isNew || this.isModified("status")) {
    this.statusHistory = this.statusHistory || [];
    this.statusHistory.push({ status: this.status, changedAt: new Date() });
  }
  next();
});

jobAgentApplicationSchema.index({ user: 1, jobSource: 1, jobRef: 1 }, { unique: true });
jobAgentApplicationSchema.index({ user: 1, status: 1, updatedAt: -1 });

module.exports = mongoose.model("JobAgentApplication", jobAgentApplicationSchema);
module.exports.JOB_AGENT_STATUS = JOB_AGENT_STATUS;
