const CONTENT_BUILDERS = {
  RAR: buildResumeAnalysisContent,
  SGR: buildSkillGapContent,
  AHR: buildApplicationHistoryContent,
  CHR: buildCandidateEvaluationContent,
  INR: buildInterviewReportContent,
  HIR: buildHiringReportContent,
  PSR: buildPlatformStatisticsContent,
  VER: buildVerificationReportContent
};

async function generateEnterpriseReport({ code, generatedBy, subject, data }) {
  const definition = REPORT_DEFINITIONS[code];
  if (!definition) throw new Error(`Unknown report code: ${code}`);

  const reportNumber = await generateReportNumber(code);
  const generatedAt = new Date();

  const doc = new PDFDocument({ size: "A4", margin: MARGIN, bufferPages: true });
  const chunks = [];

  return new Promise((resolve, reject) => {
    doc.on("data", (chunk) => chunks.push(chunk));
    doc.on("end", async () => {
      try {
        resolve({
          buffer: Buffer.concat(chunks),
          reportNumber,
          filename: `${reportNumber}.pdf`
        });
      } catch (error) {
        reject(error);
      }
    });
    doc.on("error", reject);

    (async () => {
      const meta = {
        reportTitle: definition.title,
        reportType: definition.title,
        reportNumber,
        generatedBy,
        generatedAt,
        subject
      };

      drawHeader(doc, meta);
      drawMetadata(doc, meta);
      drawExecutiveSummary(doc, definition.executiveSummary);
      drawVerificationBadge(doc, reportNumber);

      const builder = CONTENT_BUILDERS[code];
      if (builder) builder(doc, data);

      ensureSpace(doc, 80);
      doc.fillColor(COLORS.primary).font("Helvetica-Bold").fontSize(12);
      doc.text("Authorized Signature", MARGIN, doc.y, { width: CONTENT_WIDTH });
      doc.moveDown(0.4);
      doc.moveDown(2);
      doc.moveTo(MARGIN, doc.y).lineTo(MARGIN + 180, doc.y).strokeColor(COLORS.slate);
      doc.fillColor(COLORS.muted).fontSize(8).text("Authorized Signatory", MARGIN, doc.y + 6);
      doc.text(`${BRAND_NAME} Platform`, MARGIN, doc.y + 18);

      await addFootersAndQr(doc, reportNumber);
      doc.end();
    })().catch(reject);
  });
}

module.exports = { generateEnterpriseReport };
