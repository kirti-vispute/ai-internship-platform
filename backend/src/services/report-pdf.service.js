function buildHiringReportContent(doc, data, sectionStart = 3) {
  sectionHeading(doc, "Recruitment Pipeline", sectionStart);
  drawKeyValueTable(doc, [
    ["Applications", data.metrics?.applications],
    ["Shortlisted", data.metrics?.shortlisted],
    ["Rejected", data.metrics?.rejected],
    ["Selected", data.metrics?.selected],
    ["Hiring Success Rate", `${data.metrics?.hiringSuccessRate}%`]
  ]);

  sectionHeading(doc, "Recruitment Metrics", sectionStart + 1);
  const metrics = data.recruitmentMetrics || {};
  const metricRows = Object.entries(metrics)
    .filter(([, value]) => typeof value !== "object")
    .slice(0, 12)
    .map(([key, value]) => [key.replace(/([A-Z])/g, " $1").trim(), String(value)]);
  if (metricRows.length) {
    drawKeyValueTable(doc, metricRows);
  } else {
    bulletList(doc, ["Detailed analytics available in company dashboard."], "");
  }
}

