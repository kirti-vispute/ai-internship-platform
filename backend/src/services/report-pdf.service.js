const fs = require("fs");
const path = require("path");
const PDFDocument = require("pdfkit");
const QRCode = require("qrcode");
const { REPORT_DEFINITIONS, PORTAL_NAME, REPORT_VERSION } = require("../constants/report-types");
const { BRAND_NAME, BRAND_TAGLINE } = require("../constants/brand");
const { generateReportNumber } = require("./report-number.service");

const LOGO_PATH = path.join(__dirname, "../../assets/logo.png");

const COLORS = {
  primary: "#1f6fff",
  primaryDark: "#1459da",
  slate: "#0f172a",
  muted: "#64748b",
  border: "#cbd5e1",
  light: "#f8fafc",
  accent: "#22d3ee"
};

const MARGIN = 50;
const CONTENT_WIDTH = 495;

function formatDateTime(date = new Date()) {
  const d = new Date(date);
  return {
    date: d.toLocaleDateString("en-IN", { day: "2-digit", month: "short", year: "numeric" }),
    time: d.toLocaleTimeString("en-IN", { hour: "2-digit", minute: "2-digit", hour12: true })
  };
}

function drawBrandMark(doc, x, y, size = 28) {
  if (fs.existsSync(LOGO_PATH)) {
    doc.image(LOGO_PATH, x, y, { width: size, height: size });
    return;
  }
  doc.save();
  doc.roundedRect(x, y, size, size, 6).fill(COLORS.primary);
  doc.fillColor("#ffffff").font("Helvetica-Bold").fontSize(size * 0.38);
  doc.text("CS", x + size * 0.18, y + size * 0.28, { width: size * 0.64, align: "center" });
  doc.restore();
}

function drawHeader(doc, meta) {
  const { reportTitle, reportNumber, generatedBy, subject } = meta;
  const { date, time } = formatDateTime(meta.generatedAt);

  doc.save();
  doc.rect(0, 0, doc.page.width, 118).fill(COLORS.light);
  doc.restore();

  drawBrandMark(doc, MARGIN, 22, 32);
  doc.fillColor(COLORS.slate).font("Helvetica-Bold").fontSize(16);
  doc.text(BRAND_NAME, MARGIN + 42, 24);
  doc.fillColor(COLORS.muted).font("Helvetica").fontSize(9);
  doc.text(BRAND_TAGLINE, MARGIN + 42, 40, { width: 280 });
  doc.text(PORTAL_NAME, MARGIN + 42, 52, { width: 280 });

  doc.fillColor(COLORS.primary).font("Helvetica-Bold").fontSize(18);
  doc.text(reportTitle, MARGIN, 72, { width: CONTENT_WIDTH });
  doc.fillColor(COLORS.slate).font("Helvetica").fontSize(9);
  doc.text(`Report Number: ${reportNumber}`, MARGIN, 98);
  doc.text(`Generated: ${date} at ${time}`, MARGIN + 220, 98);
  doc.text(`Generated By: ${generatedBy}`, MARGIN + 380, 98, { width: 150, align: "right" });

  if (subject?.name) {
    doc.fillColor(COLORS.muted).fontSize(8);
    doc.text(
      `${subject.role || "User"}: ${subject.name}${subject.email ? ` • ${subject.email}` : ""}`,
      MARGIN,
      108,
      { width: CONTENT_WIDTH }
    );
  }

  doc.moveTo(MARGIN, 128).lineTo(MARGIN + CONTENT_WIDTH, 128).strokeColor(COLORS.border).lineWidth(1).stroke();
  doc.y = 140;
}

function drawMetadata(doc, meta) {
  const { reportType, reportNumber, generatedBy } = meta;
  const { date, time } = formatDateTime(meta.generatedAt);

  sectionHeading(doc, "Report Metadata", 1);
  const rows = [
    ["Report Type", reportType],
    ["Generated On", `${date} ${time}`],
    ["Generated By", generatedBy],
    ["Version", REPORT_VERSION],
    ["Reference Number", reportNumber],
    ["Portal Name", PORTAL_NAME]
  ];
  drawKeyValueTable(doc, rows);
  doc.moveDown(0.5);
}

function sectionHeading(doc, title, number) {
  ensureSpace(doc, 48);
  doc.fillColor(COLORS.primary).font("Helvetica-Bold").fontSize(12);
  doc.text(`${number}. ${title}`, MARGIN, doc.y, { width: CONTENT_WIDTH });
  doc.moveDown(0.35);
  doc.moveTo(MARGIN, doc.y).lineTo(MARGIN + CONTENT_WIDTH, doc.y).strokeColor(COLORS.border).lineWidth(0.5).stroke();
  doc.moveDown(0.6);
}

function ensureSpace(doc, height) {
  if (doc.y + height > doc.page.height - 80) {
    doc.addPage();
    doc.y = MARGIN;
  }
}

function drawKeyValueTable(doc, rows) {
  const startY = doc.y;
  const labelWidth = 160;
  const rowHeight = 22;

  rows.forEach((row, index) => {
    const y = startY + index * rowHeight;
    ensureSpace(doc, rowHeight + 10);
    const rowY = index === 0 ? startY : doc.y;
    doc.rect(MARGIN, rowY, CONTENT_WIDTH, rowHeight).fill(index % 2 === 0 ? "#ffffff" : COLORS.light);
    doc.fillColor(COLORS.muted).font("Helvetica-Bold").fontSize(9);
    doc.text(row[0], MARGIN + 8, rowY + 7, { width: labelWidth });
    doc.fillColor(COLORS.slate).font("Helvetica").fontSize(9);
    doc.text(String(row[1] ?? "—"), MARGIN + labelWidth + 8, rowY + 7, { width: CONTENT_WIDTH - labelWidth - 16 });
    if (index === rows.length - 1) doc.y = rowY + rowHeight;
  });
  doc.y += 8;
}

function drawDataTable(doc, headers, rows) {
  const colWidth = CONTENT_WIDTH / headers.length;
  const headerHeight = 24;
  const minRowHeight = 22;

  ensureSpace(doc, headerHeight + 40);
  let y = doc.y;

  doc.rect(MARGIN, y, CONTENT_WIDTH, headerHeight).fill(COLORS.primary);
  doc.fillColor("#ffffff").font("Helvetica-Bold").fontSize(8);
  headers.forEach((header, i) => {
    doc.text(header, MARGIN + i * colWidth + 6, y + 8, { width: colWidth - 10 });
  });
  y += headerHeight;

  rows.forEach((row, rowIndex) => {
    const cellHeights = row.map((cell, colIndex) => {
      const text = String(cell ?? "—");
      return doc.heightOfString(text, { width: colWidth - 12, fontSize: 8 });
    });
    const rowHeight = Math.max(minRowHeight, ...cellHeights) + 10;
    ensureSpace(doc, rowHeight + 10);
    y = doc.y;

    doc.rect(MARGIN, y, CONTENT_WIDTH, rowHeight).fill(rowIndex % 2 === 0 ? "#ffffff" : COLORS.light);
    doc.fillColor(COLORS.slate).font("Helvetica").fontSize(8);
    row.forEach((cell, colIndex) => {
      doc.text(String(cell ?? "—"), MARGIN + colIndex * colWidth + 6, y + 6, {
        width: colWidth - 12
      });
    });
    y += rowHeight;
    doc.y = y;
  });
  doc.y += 6;
}

function bulletList(doc, items, emptyLabel = "No data available.") {
  const list = (items || []).filter(Boolean);
  if (!list.length) {
    doc.fillColor(COLORS.muted).font("Helvetica").fontSize(9);
    doc.text(emptyLabel, MARGIN, doc.y, { width: CONTENT_WIDTH });
    doc.moveDown(0.5);
    return;
  }
  doc.fillColor(COLORS.slate).font("Helvetica").fontSize(9);
  list.forEach((item) => {
    ensureSpace(doc, 20);
    doc.text(`• ${String(item)}`, MARGIN + 4, doc.y, { width: CONTENT_WIDTH - 8 });
    doc.moveDown(0.25);
  });
}

function drawExecutiveSummary(doc, summary) {
  sectionHeading(doc, "Executive Summary", 2);
  doc.fillColor(COLORS.slate).font("Helvetica").fontSize(10);
  doc.text(summary, MARGIN, doc.y, { width: CONTENT_WIDTH, align: "justify", lineGap: 3 });
  doc.moveDown(0.8);
}

function drawWatermark(doc) {
  doc.save();
  doc.rotate(-32, { origin: [doc.page.width / 2, doc.page.height / 2] });
  doc.fillColor("#94a3b8").font("Helvetica-Bold").fontSize(46).opacity(0.08);
  doc.text(BRAND_NAME, 95, doc.page.height / 2 - 28, { width: 400, align: "center" });
  doc.fontSize(14).opacity(0.06);
  doc.text(`${BRAND_NAME} Verified · ${BRAND_TAGLINE}`, 95, doc.page.height / 2 + 18, {
    width: 400,
    align: "center"
  });
  doc.restore();
  doc.opacity(1);
}

function drawVerificationBadge(doc, reportNumber) {
  ensureSpace(doc, 70);
  const x = MARGIN + CONTENT_WIDTH - 130;
  const y = doc.y;
  doc.roundedRect(x, y, 120, 52, 4).strokeColor(COLORS.primary).lineWidth(1).stroke();
  doc.fillColor(COLORS.primary).font("Helvetica-Bold").fontSize(8);
  doc.text("VERIFIED REPORT", x + 10, y + 10, { width: 100, align: "center" });
  doc.fillColor(COLORS.muted).font("Helvetica").fontSize(7);
  doc.text(reportNumber, x + 8, y + 26, { width: 104, align: "center" });
  doc.y = Math.max(doc.y, y + 60);
}

async function addFootersAndQr(doc, reportNumber) {
  let qrBuffer = null;
  try {
    qrBuffer = await QRCode.toBuffer(reportNumber, { margin: 1, width: 72 });
  } catch {
    qrBuffer = null;
  }

  const range = doc.bufferedPageRange();
  for (let i = range.start; i < range.start + range.count; i += 1) {
    doc.switchToPage(i);
    drawWatermark(doc);

    const footerY = doc.page.height - 42;
    doc.moveTo(MARGIN, footerY - 8).lineTo(MARGIN + CONTENT_WIDTH, footerY - 8).strokeColor(COLORS.border).lineWidth(0.5).stroke();
    doc.fillColor(COLORS.muted).font("Helvetica").fontSize(7);
    doc.text(`${BRAND_NAME} • Confidential Report • Generated Automatically`, MARGIN, footerY, {
      width: CONTENT_WIDTH - 90
    });
    doc.text(`Page ${i - range.start + 1} of ${range.count}`, MARGIN, footerY + 10, {
      width: CONTENT_WIDTH,
      align: "right"
    });

    if (qrBuffer && i === range.start) {
      doc.image(qrBuffer, MARGIN + CONTENT_WIDTH - 58, footerY - 4, { width: 36, height: 36 });
    }
  }
}

